using System.Reflection;
using System.Text;
using Application;
using Application.Interfaces.Messaging;

// Build-time code generator: scans the Application assembly for marker interfaces and
// emits a partial JsonSerializerContext with the [JsonSerializable] attributes, so that
// API request/response types are registered automatically instead of by hand.
//
// Usage:
//   dotnet run -- --output <file.g.cs> --namespace <ContextNs> --api-response-namespace <ApiResponseNs>

var options = ParseArgs(args);
string outputPath = Require(options, "output");
string contextNamespace = Require(options, "namespace");
string apiResponseNamespace = Require(options, "api-response-namespace");

Type[] allTypes;
try
{
    allTypes = typeof(IApiResponse).Assembly.GetTypes();
}
catch (ReflectionTypeLoadException ex)
{
    allTypes = ex.Types.Where(t => t is not null).Cast<Type>().ToArray();
}

static bool IsConcrete(Type t)
    => t is { IsAbstract: false, IsInterface: false, IsGenericTypeDefinition: false };

static string Global(Type t) => "global::" + t.FullName!.Replace('+', '.');

string[] singleResponses = allTypes
    .Where(t => IsConcrete(t) && typeof(IApiResponse).IsAssignableFrom(t))
    .Select(Global).OrderBy(x => x, StringComparer.Ordinal).ToArray();

string[] collectionResponses = allTypes
    .Where(t => IsConcrete(t) && typeof(IApiCollectionResponse).IsAssignableFrom(t))
    .Select(Global).OrderBy(x => x, StringComparer.Ordinal).ToArray();

string[] requests = allTypes
    .Where(t => IsConcrete(t) && typeof(IValidationCommand).IsAssignableFrom(t))
    .Select(Global).OrderBy(x => x, StringComparer.Ordinal).ToArray();

string apiResponse = $"global::{apiResponseNamespace}.ApiResponse";
string apiCollectionResponse = $"global::{apiResponseNamespace}.ApiCollectionResponse";

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated/>");
sb.AppendLine("// Generated by tools/JsonSerializerContextGenerator. Do not edit by hand.");
sb.AppendLine("#nullable enable");
sb.AppendLine("#pragma warning disable");
sb.AppendLine();
sb.AppendLine("using System.Text.Json.Serialization;");
sb.AppendLine();
sb.AppendLine($"namespace {contextNamespace};");
sb.AppendLine();

// ---- Responses ----
AppendOptions(sb);
sb.AppendLine($"[JsonSerializable(typeof({apiResponse}))]");
sb.AppendLine($"[JsonSerializable(typeof({apiResponse}<global::System.Guid>))]");
foreach (var t in singleResponses)
    sb.AppendLine($"[JsonSerializable(typeof({apiResponse}<{t}>))]");
foreach (var t in collectionResponses)
    sb.AppendLine($"[JsonSerializable(typeof({apiCollectionResponse}<{t}>))]");
sb.AppendLine("public partial class ApiResponseJsonSourceGenerator : JsonSerializerContext;");
sb.AppendLine();

// ---- Requests ----
AppendOptions(sb);
foreach (var t in requests)
    sb.AppendLine($"[JsonSerializable(typeof({t}))]");
sb.AppendLine("public partial class ApiRequestJsonSourceGenerator : JsonSerializerContext;");

string generated = sb.ToString();

// Always write (overwrite) so the file timestamp updates for MSBuild incremental builds.
// Content is deterministic (sorted), so git sees no diff unless the registered types change.
Directory.CreateDirectory(Path.GetDirectoryName(outputPath)!);
File.WriteAllText(outputPath, generated);

Console.WriteLine(
    $"Generated {outputPath}: {singleResponses.Length} single + {collectionResponses.Length} collection responses, {requests.Length} requests.");
return 0;

static void AppendOptions(StringBuilder sb)
    => sb.AppendLine(
        "[JsonSourceGenerationOptions(PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase, GenerationMode = JsonSourceGenerationMode.Default)]");

static Dictionary<string, string> ParseArgs(string[] args)
{
    var result = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
    for (int i = 0; i < args.Length - 1; i++)
    {
        if (args[i].StartsWith("--", StringComparison.Ordinal))
            result[args[i][2..]] = args[++i];
    }
    return result;
}

static string Require(Dictionary<string, string> options, string key)
    => options.TryGetValue(key, out var value)
        ? value
        : throw new ArgumentException($"Missing required argument --{key}");
